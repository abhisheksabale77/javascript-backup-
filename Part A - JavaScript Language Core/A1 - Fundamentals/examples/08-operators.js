// Arithmetic, comparison, logical, and ternary operators.
// Run: node examples/08-operators.js

console.log(7 + 3); // Output: 10
console.log(7 % 3); // Output: 1 (remainder)
console.log(2 ** 3); // Output: 8 (power)

console.log(5 > 3 && 2 < 4); // Output: true
console.log(5 > 3 || false); // Output: true

const age = 20;
console.log(age >= 18 ? "adult" : "minor"); // Output: adult

console.log("5" + 2); // Output: 52 (string join)
console.log("5" - 2); // Output: 3 (number subtraction)

